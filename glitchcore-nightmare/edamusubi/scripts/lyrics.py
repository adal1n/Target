SMALL = set('ゃゅょぁぃぅぇぉ')
def morae(kana):
    out = []  # list of (mora, word_end)
    for w in kana.split():
        ms = []
        for ch in w:
            if ch in SMALL and ms: ms[-1] += ch
            else: ms.append(ch)
        out += [(m, i == len(ms) - 1) for i, m in enumerate(ms)]
    return out
